//! What an agent can do through Pigeonnier: see what is waiting, and hand a manual action over with
//! the conventions already applied, so they no longer have to be repeated in its instructions.

use std::sync::Arc;

use anyhow::Result;
use chrono::Local;
use pigeonnier_core::engine::{Engine, NewAction};
use pigeonnier_core::item::Priority;
use pigeonnier_core::viewmodel::ProjectVm;
use rmcp::handler::server::wrapper::Parameters;
use rmcp::model::{CallToolResult, ContentBlock, ServerCapabilities, ServerConfig};
use rmcp::{ErrorData, ServerHandler, ServiceExt, schemars, tool, tool_handler, tool_router};
use serde::Deserialize;
use serde_json::json;

#[derive(Debug, Deserialize, schemars::JsonSchema)]
struct ListItems {
    /// Only this project, by id. Leave out for all of them.
    project: Option<String>,
}

#[derive(Debug, Deserialize, schemars::JsonSchema)]
struct AddManualAction {
    /// The id of the project, as `list_items` gives it.
    project: String,
    /// What the person has to do.
    title: String,
    /// When, in Todoist's language, such as "friday" or "2026-12-01".
    due: Option<String>,
    /// From 1, the most urgent, to 4.
    priority: Option<u8>,
    /// The pull request this action relates to.
    pr_url: Option<String>,
}

#[derive(Clone)]
struct Server {
    engine: Arc<Engine>,
}

fn failure(error: impl std::fmt::Display) -> ErrorData {
    ErrorData::internal_error(error.to_string(), None)
}

fn describe(projects: &[ProjectVm]) -> serde_json::Value {
    let items = |project: &ProjectVm| {
        project
            .items
            .iter()
            .chain(project.bots.iter().flat_map(|bots| &bots.items))
            .map(|item| {
                json!({
                    "id": item.id,
                    "title": item.title,
                    "kind": item.kind,
                    "context": item.context,
                    "url": item.url,
                    "priority": item.priority,
                    "state": item.state_label,
                    "due": item.due_label,
                })
            })
            .collect::<Vec<_>>()
    };
    projects
        .iter()
        .map(|project| {
            json!({
                "id": project.id,
                "name": project.name,
                "action_required": project.action_count,
                "overdue": project.overdue_count,
                "items": items(project),
            })
        })
        .collect()
}

#[tool_router]
impl Server {
    fn new(engine: Engine) -> Self {
        Self {
            engine: Arc::new(engine),
        }
    }

    #[tool(
        description = "What is waiting for the person, grouped by project and most urgent first: \
        pull requests, manual actions and roadmap items."
    )]
    async fn list_items(
        &self,
        Parameters(arguments): Parameters<ListItems>,
    ) -> Result<CallToolResult, ErrorData> {
        self.engine.refresh().await.map_err(failure)?;
        let snapshot = self
            .engine
            .snapshot("all", Local::now().fixed_offset())
            .map_err(failure)?;
        let projects: Vec<ProjectVm> = snapshot
            .projects
            .into_iter()
            .filter(|project| {
                arguments
                    .project
                    .as_ref()
                    .is_none_or(|id| *id == project.id)
            })
            .collect();
        let text =
            json!({ "projects": describe(&projects), "issues": snapshot.issues }).to_string();
        Ok(CallToolResult::success(vec![ContentBlock::text(text)]))
    }

    #[tool(
        description = "Ask the person to do something by hand: creates a Todoist task in the \
        section of the project, with the label that marks actions asked by an agent."
    )]
    async fn add_manual_action(
        &self,
        Parameters(arguments): Parameters<AddManualAction>,
    ) -> Result<CallToolResult, ErrorData> {
        let priority = match arguments.priority {
            None => None,
            Some(1) => Some(Priority::P1),
            Some(2) => Some(Priority::P2),
            Some(3) => Some(Priority::P3),
            Some(4) => Some(Priority::P4),
            Some(other) => {
                return Err(ErrorData::invalid_params(
                    format!("priority must be 1 to 4, not {other}"),
                    None,
                ));
            }
        };
        self.engine
            .add_manual_action(NewAction {
                project: arguments.project,
                title: arguments.title,
                due: arguments.due,
                priority,
                pr_url: arguments.pr_url,
            })
            .await
            .map_err(failure)?;
        Ok(CallToolResult::success(vec![ContentBlock::text("created")]))
    }
}

#[allow(clippy::unused_async_trait_impl)] // Generated by the macro.
#[tool_handler]
impl ServerHandler for Server {
    fn get_info(&self) -> ServerConfig {
        ServerConfig::new(ServerCapabilities::builder().enable_tools().build()).with_instructions(
            "Pigeonnier knows what is waiting for the person, project by project.",
        )
    }
}

pub async fn serve(engine: Engine) -> Result<()> {
    let service = Server::new(engine).serve(rmcp::transport::stdio()).await?;
    service.waiting().await?;
    Ok(())
}
